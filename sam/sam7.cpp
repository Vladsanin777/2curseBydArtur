#include <iostream>
#include <regex>
#include <string>

int main() {
    setlocale(LC_ALL, "Russian");
    
    // Регулярное выражение для проверки домашнего адреса
    std::regex addressPattern(
        R"(^(?i)(г\.\s+[А-Яа-яЁё\-]+|город\s+[А-Яа-яЁё\-]+),\s+(ул\.\s+[А-Яа-яЁё\-]+|улица\s+[А-Яа-яЁё\-]+),\s+(д\.?\s*\d+|дом\s+\d+)(,\s+(кв\.?\s*\d+|квартира\s+\d+))?$)"
    );
    
    // Массив тестовых строк
    const int TESTS_COUNT = 7;
    std::string tests[TESTS_COUNT] = {
        "г. Волгоград, ул. Невская, д.18, кв.43",
        "Город Москва, улица Молодежная, дом 20, квартира 50",
        "г. Санкт-Петербург, ул. Ленина, д. 5",
        "город Казань, ул. Баумана, дом 10, кв. 12",
        "г. Волгоград ул. Невская д.18",
        "Москва, ул. Тверская, д.1",
        "г. Волгоград, ул. Невская, д.18, кв.43, лит.А"
    };
    
    std::cout << "=== Проверка адресов (вариант 2) ===\n\n";
    
    for (int i = 0; i < TESTS_COUNT; i++) {
        bool match = std::regex_match(tests[i], addressPattern);
        std::cout << "Адрес: " << tests[i] << "\n";
        std::cout << "Результат: " << (match ? "Корректный" : "Некорректный") << "\n\n";
    }
    
    return 0;
}
